"""Generate docs/api-documentation.md from the app itself (routes + OpenAPI schema).

    uv run python -m scripts.gen_api_docs            # rewrite the file
    uv run python -m scripts.gen_api_docs --check    # CI: fail if the file is out of date

Auth and rate limits are read from each route's dependencies, not written by hand, so the table
can't drift from the code.
"""

import argparse
import sys
from collections.abc import Iterator
from pathlib import Path
from typing import Any

from fastapi.routing import APIRoute

from app.main import app

OUT = Path(__file__).resolve().parents[2] / "docs" / "api-documentation.md"

HEADER = """# API reference

Generated by `backend/scripts/gen_api_docs.py` from the application's routes and OpenAPI schema; CI fails
if this file is out of date. Interactive docs: `/docs` (Swagger UI) and `/redoc` on the API (port 8080
when run natively, or through the site at `http://localhost:8090/docs` in Docker).

**Conventions**
- Base path `/api/v1` (health checks are unversioned). JSON in and out.
- **Auth** column: *public* needs nothing; *user* needs `Authorization: Bearer <access_token>` from
  `POST /api/v1/auth/login`; *admin* also needs an admin account (`python -m app.cli make-admin <email>`).
- **Limit** column: the rate-limit rule applied (`app/core/rate_limit.py`), per address (*ip*) or per user.
  Over the limit: `429` with a `Retry-After` header.
- Errors always use one envelope: `{"error": {"code", "message", "details", "request_id"}}`. Codes:
  `validation_error` (422), `unauthenticated` (401), `forbidden` (403), `not_found` (404), `conflict` /
  `job_unavailable` (409), `payload_too_large` (413), `unsupported_media_type` (415), `rate_limited` (429),
  `upstream_unavailable` (503), `internal_error` (500).
- Every response carries `X-Request-ID` (send your own to correlate logs).
- Lists that can grow (jobs, saved jobs) use opaque `next_cursor` keyset pagination.
"""


def _routes(items: Any) -> Iterator[Any]:
    """Every API route with its full path. FastAPI 0.16x wraps included routers lazily
    (`_IncludedRouter`), so walk `effective_candidates()` recursively instead of `app.routes`."""
    for item in items:
        if isinstance(item, APIRoute) or type(item).__name__ == "_EffectiveRouteContext":
            yield item
        elif hasattr(item, "effective_candidates"):
            yield from _routes(item.effective_candidates())


def _deps(route: Any) -> list[str]:
    """Qualified names of every dependency callable in the route's tree."""
    names: list[str] = []
    stack = list(route.dependant.dependencies)
    while stack:
        d = stack.pop()
        if d.call is not None:
            names.append(getattr(d.call, "__qualname__", ""))
        stack.extend(d.dependencies)
    return names


def _auth(deps: list[str]) -> str:
    if "get_current_admin" in deps:
        return "admin"
    return "user" if "get_current_user" in deps else "public"


def _limit(route: Any) -> str:
    for d in route.dependant.dependencies:
        q = getattr(d.call, "__qualname__", "")
        if q.startswith(("by_ip.", "by_user.")):
            rule = d.call.__closure__[0].cell_contents if d.call and d.call.__closure__ else None
            who = "ip" if q.startswith("by_ip.") else "user"
            if rule is not None:
                return f"{rule.name}: {rule.limit}/{_window(rule.window_seconds)} per {who}"
    return ""


def _first_sentence(text: str) -> str:
    """The docstring's first sentence, joined across wrapped lines (pipes escaped for tables)."""
    para = " ".join(text.strip().split("\n\n")[0].split())
    cut = para.find(". ")
    return (para[: cut + 1] if cut != -1 else para).replace("|", "\\|")


def _window(seconds: int) -> str:
    return {60: "min", 3600: "h"}.get(seconds, f"{seconds // 60} min")


def render() -> str:
    schema = app.openapi()
    groups: dict[str, list[str]] = {}
    for route in _routes(app.routes):
        if not route.include_in_schema:
            continue
        op_all = schema["paths"].get(route.path_format, {})
        for method in sorted(route.methods - {"HEAD"}):
            op = op_all.get(method.lower(), {})
            tag = (op.get("tags") or ["other"])[0]
            text = _first_sentence(op.get("description") or op.get("summary") or "")
            row = f"| {method} | `{route.path_format}` | {text} | {_auth(_deps(route))} | {_limit(route)} |"
            groups.setdefault(tag, []).append(row)
    out = [HEADER]
    total = sum(len(v) for v in groups.values())
    out.append(f"**{total} endpoints.**\n")
    for tag, rows in groups.items():
        out.append(
            f"## {tag}\n\n| Method | Path | Description | Auth | Limit |\n|---|---|---|---|---|"
        )
        out.extend(rows)
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    text = render()
    if parser.parse_args().check:
        if not OUT.exists() or OUT.read_text() != text:
            print(
                "docs/api-documentation.md is out of date: run `uv run python -m scripts.gen_api_docs`"
            )
            return 1
        print("api docs up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
